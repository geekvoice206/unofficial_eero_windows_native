        private void OpenChat(bool history = false)
        {
            if (String.IsNullOrEmpty(networkUrl)) throw new InvalidOperationException("Select a network before opening chat or its support history.");
            var existing = OwnedWindows.OfType<ConversationWindow>().FirstOrDefault();
            if (existing != null) { existing.Activate(); return; }
            new ConversationWindow(api, NetworkId, J.S(network, "name"), preview, history) { Owner = this }.Show();
        }
        private void ChatPage(bool history)
        {
            Sub(history ? "Support history" : "Chat with eero");
            page.Children.Add(Card(Text("Ask eero about your network, review previous conversations and respond to requested changes. Availability is controlled by eero for your account, region and network.", 15)));
            ActionRow(LocalButton(history ? "Open support history" : "Open chat", delegate { OpenChat(history); }), LocalButton("Official support", delegate { OpenServiceWindow("eero support", "https://www.eero.com/support"); }));
