            page.Children.Add(Text("Alexa opens in its own window. Available features depend on your Amazon account and region.", 13, "#64738A"));
        }
        private sealed class ConversationWindow : Window
        {
            private readonly EeroApi api;
            private readonly string networkId;
            private readonly bool sample;
            private readonly StackPanel messages;
            private readonly ScrollViewer scroll;
            private readonly TextBox input;
            private readonly TextBlock status;
            private readonly Button send, stop, fresh, reload;
            private readonly ComboBox history;
            private readonly Dictionary<string, TextBlock> deltas = new Dictionary<string, TextBlock>();
            private readonly HashSet<string> rendered = new HashSet<string>();
            private readonly HashSet<string> feedback = new HashSet<string>();
            private readonly HashSet<string> answered = new HashSet<string>();
            private readonly Dictionary<string, System.Windows.UIElement> widgets = new Dictionary<string, System.Windows.UIElement>();
            private CancellationTokenSource cancellation;
            private string conversationId, mcpToken;
            private bool running, closed, fillingHistory, waitingForPermission;
            public ConversationWindow(EeroApi api, string networkId, string networkName, bool sample, bool showHistory)
            {
                this.api = api; this.networkId = networkId; this.sample = sample;
                Title = "Chat with eero · " + networkName; Width = 960; Height = 820; MinWidth = 700; MinHeight = 620; WindowStartupLocation = WindowStartupLocation.CenterOwner;
                SourceInitialized += delegate { Program.ThemeNativeWindow(this); };
                var root = new Grid { Margin = new Thickness(22), Background = Brush("#F4F6FA") }; root.RowDefinitions.Add(new RowDefinition { Height = GridLength.Auto }); root.RowDefinitions.Add(new RowDefinition()); root.RowDefinitions.Add(new RowDefinition { Height = GridLength.Auto });
                var top = new StackPanel(); top.Children.Add(Text("Chat with eero", 27, "#17263C", true)); top.Children.Add(Text(networkName + (sample ? " · Sample conversation" : " · Replies are generated by eero's assistant"), 13, "#64738A"));
                var toolbar = new WrapPanel(); fresh = Control("New chat", async delegate { Reset(); await Recommendations(); }); reload = Control("Reload history", LoadHistory); toolbar.Children.Add(fresh); toolbar.Children.Add(reload); top.Children.Add(toolbar);
                history = new ComboBox { DisplayMemberPath = "Label", MinWidth = 260, HorizontalAlignment = HorizontalAlignment.Stretch };
                history.SelectionChanged += async delegate { if (fillingHistory || running || history.SelectedItem == null) return; var item = (HistoryItem)history.SelectedItem; await Perform(async delegate { await LoadConversation(item.Id); }); }; top.Children.Add(history); root.Children.Add(top);
                messages = new StackPanel { Margin = new Thickness(0, 15, 0, 15) }; scroll = new ScrollViewer { Content = messages, VerticalScrollBarVisibility = ScrollBarVisibility.Auto, HorizontalScrollBarVisibility = ScrollBarVisibility.Disabled }; Grid.SetRow(scroll, 1); root.Children.Add(scroll);
                var bottom = new StackPanel(); input = new TextBox { AcceptsReturn = true, TextWrapping = TextWrapping.Wrap, MinHeight = 76, MaxHeight = 180, MaxLength = 8000, VerticalScrollBarVisibility = ScrollBarVisibility.Auto }; bottom.Children.Add(input);
                input.KeyDown += async delegate(object sender, KeyEventArgs e) { if (e.Key == Key.Enter && Keyboard.Modifiers == ModifierKeys.Control) { e.Handled = true; await Perform(SendMessage); } };
                var actions = new WrapPanel(); send = Control("Send · Ctrl+Enter", SendMessage); stop = Control("Stop reply", async delegate { if (cancellation != null) cancellation.Cancel(); await Task.FromResult(0); }); stop.IsEnabled = false; actions.Children.Add(send); actions.Children.Add(stop); bottom.Children.Add(actions);
                status = Text("Your chat is sent to eero. Review any requested network changes before approving.", 13, "#64738A"); bottom.Children.Add(status); Grid.SetRow(bottom, 2); root.Children.Add(bottom); Content = root;
                Closed += delegate { closed = true; if (cancellation != null) cancellation.Cancel(); mcpToken = conversationId = null; deltas.Clear(); messages.Children.Clear(); input.Clear(); };
                Loaded += async delegate
                {
                    if (sample) { Preview(); return; }
                    await Perform(async delegate { await LoadHistory(); if (!showHistory) await Recommendations(); });
                };
            }
            private sealed class HistoryItem { public string Id { get; set; } public string Label { get; set; } }
            private Button Control(string label, Func<Task> action)
            {
                var button = new Button { Content = label, Margin = new Thickness(0, 7, 10, 7) };
                button.Click += async delegate { await Perform(action); }; return button;
            }
            private async Task Perform(Func<Task> action)
            {
                if (running || closed) return;
                running = true; send.IsEnabled = fresh.IsEnabled = reload.IsEnabled = history.IsEnabled = input.IsEnabled = false;
                try { await action(); }
                catch (Exception e) { if (!closed) status.Text = cancellation != null && cancellation.IsCancellationRequested ? "Reply stopped. Reload history to see the server's saved conversation before sending again." : ConversationContracts.Error(e); }
                finally { running = false; if (!closed) { send.IsEnabled = fresh.IsEnabled = reload.IsEnabled = history.IsEnabled = input.IsEnabled = true; stop.IsEnabled = false; input.Focus(); } }
            }
            private void Reset()
            {
                conversationId = null; messages.Children.Clear(); deltas.Clear(); rendered.Clear(); answered.Clear(); feedback.Clear(); widgets.Clear(); waitingForPermission = false;
                fillingHistory = true; history.SelectedIndex = -1; fillingHistory = false;
            }
            private async Task LoadHistory()
            {
                if (sample) { Preview(); return; }
                object data = await api.Send("GET", "/2.2/conversations?networkId=" + Uri.EscapeDataString(networkId) + "&excludeEmpty=true");
                if (closed) return;
                fillingHistory = true; history.Items.Clear();
                foreach (object row in J.List(J.Get(data, "conversations")))
                {
                    string id = J.S(row, "conversation_id"); if (id.Length == 0) continue;
                    history.Items.Add(new HistoryItem { Id = id, Label = J.First(row, "description", "created").NullIfEmpty() ?? "Previous conversation" });
                }
                fillingHistory = false; status.Text = history.Items.Count == 0 ? "No saved conversations were returned." : "Choose a conversation to read its history.";
                if (!String.IsNullOrEmpty(conversationId)) await LoadConversation(conversationId);
            }
            private async Task LoadConversation(string id)
            {
                object data = await api.Send("GET", "/2.2/conversations/" + Uri.EscapeDataString(id)); if (closed) return;
                Reset(); conversationId = J.S(data, "conversation_id").NullIfEmpty() ?? id;
                foreach (object row in J.List(J.Get(data, "message_history")))
                {
                    object message = J.Get(row, "message"); string messageId = J.S(row, "message_id");
                    if (message != null) { Bubble(J.S(message, "sender") == "USER" ? "You" : "eero", J.S(message, "content"), messageId); if (J.S(message, "sender") != "USER") Feedback(messageId); }
                    else if (J.Get(row, "permission_request") != null) Bubble("Previous request", J.First(J.Get(row, "permission_request"), "friendly_sentence", "content"), null);
                    else if (J.Get(row, "permission_grant") != null) Bubble("Previous decision", J.B(row, "permission_grant", "approved") ? "Approved" : "Declined", null);
                    else if (J.Get(row, "widget_event") != null) Widget(J.Get(row, "widget_event"), false);
                }
                status.Text = "Conversation loaded. You can continue below."; scroll.ScrollToEnd();
            }
            private async Task Recommendations()
            {
                if (sample) return;
                object data = await api.Send("GET", "/2.2/conversations/recommended?networkId=" + Uri.EscapeDataString(networkId)); if (closed) return;
                foreach (object row in J.List(J.Get(data, "recommendations")))
                {
                    string prompt = J.S(row, "suggested_prompt"); if (prompt.Length == 0) continue;
                    messages.Children.Add(Control(J.First(row, "title", "cta_text").NullIfEmpty() ?? prompt, async delegate { input.Text = prompt; await SendMessage(); }));
                }
            }
            private async Task<string> Token()
            {
                // Tokens stay in memory and are refreshed for each submitted turn.
                try { object value = await api.Send("POST", "/2.2/conversations/token", J.Obj("refresh_token", "")); return J.S(value, "access_token").NullIfEmpty(); }
                catch (ApiException e) { if (e.SessionExpired) throw; return null; }
            }
            private async Task SendMessage()
            {
                string message = input.Text.Trim(); ConversationContracts.Request(networkId, conversationId, message);
                if (sample) { Bubble("You", message, null); input.Clear(); Bubble("eero", "This is a local sample. Sign in to send messages to eero.", null); return; }
                mcpToken = await Token(); if (closed) return;
                Bubble("You", message, null); input.Clear();
                await Stream(ConversationContracts.Request(networkId, conversationId, message, mcpToken));
            }
            private async Task Stream(object body)
            {
                if (sample) return;
                deltas.Remove("stream-reply");
                using (var source = new CancellationTokenSource(TimeSpan.FromMinutes(3)))
                {
                    waitingForPermission = false; cancellation = source; stop.IsEnabled = true; status.Text = "eero is replying…";
                    try { await api.StreamConversation(body, value => Dispatcher.Invoke(new Action(delegate { if (!closed) Receive(value); })), source.Token); if (!closed) status.Text = "Reply finished."; }
                    catch (Exception)
                    {
                        if (!source.IsCancellationRequested) throw;
                        if (!closed) status.Text = waitingForPermission ? "eero is waiting for your decision. Review the request above." : "Reply stopped. Reload history before sending again.";
                    }
                    finally { cancellation = null; if (!closed) stop.IsEnabled = false; }
                }
            }
            private TextBlock Bubble(string sender, string content, string id)
            {
                var stack = new StackPanel(); stack.Children.Add(Text(sender, 13, "#64738A", true)); var text = Text(content, 15, "#17263C"); stack.Children.Add(text);
                messages.Children.Add(new Border { Background = sender == "You" ? Brush(UiPreferences.Dark ? "#233654" : "#EEF3FF") : Surface, CornerRadius = new CornerRadius(8), Padding = new Thickness(18), Margin = new Thickness(0, 0, 0, 12), Child = stack });
                if (!String.IsNullOrEmpty(id)) deltas[id] = text; scroll.ScrollToEnd(); return text;
            }
            private void Receive(object value)
            {
                if (J.S(value, "conversation_id").Length > 0) conversationId = J.S(value, "conversation_id");
                string type = J.S(value, "type"), id = J.S(value, "message_id");
                if (type == "Error") throw new InvalidOperationException("eero could not finish this reply. Reload history before trying again.");
                if (type == "InitialMessage" || type == "MessageDelta")
                {
                    string key = id.Length > 0 ? id : "stream-reply"; TextBlock target;
                    if (!deltas.TryGetValue(key, out target)) target = Bubble("eero", "", key);
                    if (type == "InitialMessage") target.Text = J.S(value, "content"); else target.Text += J.S(value, "content");
                    if (J.B(value, "finished")) Feedback(id); scroll.ScrollToEnd();
                }
                if (type == "ToolUse" || type == "Reasoning") status.Text = "eero is checking your request…";
                if (J.Get(value, "permission_request") != null)
                { Permission(J.Get(value, "permission_request")); waitingForPermission = true; if (cancellation != null) cancellation.Cancel(); }
                if (J.Get(value, "widget_event") != null) Widget(J.Get(value, "widget_event"), true);
            }
            private void Feedback(string id)
            {
                if (id.Length == 0 || !feedback.Add(id)) return;
                var row = new WrapPanel();
                foreach (bool positive in new[] { true, false })
                {
                    bool choice = positive;
                    row.Children.Add(Control(choice ? "Helpful" : "Not helpful", async delegate { if (!sample) await api.Send("PUT", "/2.2/conversations/feedbacks", J.Obj("message_id", id, "positive", choice)); status.Text = "Feedback saved."; }));
                }
                messages.Children.Add(row);
            }
            private void Permission(object permission)
            {
                string id = J.S(permission, "interrupt_id"); if (id.Length == 0 || !rendered.Add("permission:" + id)) return;
                Bubble("Permission required", J.S(permission, "friendly_sentence") + "\n" + String.Join("\n", J.List(J.Get(permission, "tool_descriptions")).Select(v => J.S(v))), null);
                var row = new WrapPanel();
                foreach (bool approve in new[] { false, true })
                {
                    bool choice = approve;
                    row.Children.Add(Control(choice ? "Approve request…" : "Decline request", async delegate
                    {
                        if (answered.Contains(id)) { status.Text = "This request has already been answered."; return; }
                        if (choice && MessageBox.Show(this, J.S(permission, "friendly_sentence") + "\n\n" + String.Join("\n", J.List(J.Get(permission, "tool_descriptions")).Select(v => J.S(v))), "Approve eero's requested changes?", MessageBoxButton.YesNo, MessageBoxImage.Question, MessageBoxResult.No) != MessageBoxResult.Yes) return;
                        if (sample) { answered.Add(id); row.IsEnabled = false; status.Text = "Sample decision only."; return; }
                        mcpToken = await Token(); answered.Add(id); row.IsEnabled = false;
                        await Stream(ConversationContracts.Request(networkId, conversationId, null, mcpToken, J.Obj("approved", choice, "interrupt_id", id)));
                    }));
                }
                messages.Children.Add(row);
            }
            private void Widget(object widget, bool active)
            {
                string id = J.S(widget, "instance_id"), action = J.S(widget, "action");
                System.Windows.UIElement previous;
                if (widgets.TryGetValue(id, out previous)) { messages.Children.Remove(previous); widgets.Remove(id); }
                if (action.Equals("remove", StringComparison.OrdinalIgnoreCase) || action.Equals("delete", StringComparison.OrdinalIgnoreCase)) return;
                object properties = J.Get(widget, "properties");
                var panel = new StackPanel(); panel.Children.Add(Text("eero · " + J.S(widget, "widget_type"), 13, "#64738A", true));
                panel.Children.Add(Text(J.S(widget, "content_summary").NullIfEmpty() ?? J.First(properties, "prompt_text", "title", "description"), 15));
                foreach (string field in new[] { "name", "location", "model", "status", "connected", "connection_type", "connection_state", "device_type", "is_guest", "is_private", "score_bars", "mesh_quality_bars", "wan_type", "eero", "port_number", "negotiated_speed", "total_devices", "paused_devices", "accessory_type", "bars", "cellular_backup_status", "configuration_status" })
                { string value = J.S(properties, field); if (value.Length > 0) panel.Children.Add(Text(Human(field) + ": " + value, 13, "#64738A")); }
                foreach (object choice in J.List(J.Get(properties, "choices")))
                {
                    string prompt = J.S(choice); if (!active || prompt.Length == 0) continue;
                    panel.Children.Add(Control(prompt, async delegate { input.Text = prompt; await SendMessage(); }));
                }
                foreach (object contact in J.List(J.Get(properties, "contacts"))) panel.Children.Add(Text(J.S(contact, "title") + ": " + J.S(contact, "content"), 14));
                var card = Card(panel); messages.Children.Add(card); widgets[id] = card; scroll.ScrollToEnd();
            }
            internal void Preview()
            {
                Reset(); Bubble("You", "Check my connectivity", null); Bubble("eero", "Your sample network is online. The gateway and two wireless eeros are connected.", "sample-reply"); Feedback("sample-reply");
                Permission(J.Obj("interrupt_id", "sample-permission", "friendly_sentence", "May I run a connection diagnostic?", "tool_descriptions", new[] { "Check internet health on the selected network." }));
                status.Text = "Sample conversation · No account requests or changes.";
            }
        }
